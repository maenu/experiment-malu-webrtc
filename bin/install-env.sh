#!/usr/bin/env bash

cd "$(dirname "$0")/../.."

if [ $NODE_ENV != "development" ] && [ $NODE_ENV != "production" ]
then
  echo "NODE_ENV must be set to 'development' or 'production'."
  exit 1
fi

source "bin/install-env.$NODE_ENV.sh"

cat << EOF > ".env.$NODE_ENV"
NODE_ENV=$NODE_ENV
EXPERIMENT_MALU_WEBRTC_HOST=$EXPERIMENT_MALU_WEBRTC_HOST
EXPERIMENT_MALU_WEBRTC_CA_CERT=$EXPERIMENT_MALU_WEBRTC_CA_CERT
EXPERIMENT_MALU_WEBRTC_CA_KEY=$EXPERIMENT_MALU_WEBRTC_CA_KEY
EXPERIMENT_MALU_WEBRTC_CA_HOST=$EXPERIMENT_MALU_WEBRTC_CA_HOST
EXPERIMENT_MALU_WEBRTC_PEERJS_PORT=$EXPERIMENT_MALU_WEBRTC_PEERJS_PORT
EXPERIMENT_MALU_WEBRTC_PEERJS_PATH=$EXPERIMENT_MALU_WEBRTC_PEERJS_PATH
EXPERIMENT_MALU_WEBRTC_PEERJS_KEY=$EXPERIMENT_MALU_WEBRTC_PEERJS_KEY
EXPERIMENT_MALU_WEBRTC_PEERJS_EXTRA=$EXPERIMENT_MALU_WEBRTC_PEERJS_EXTRA
EXPERIMENT_MALU_WEBRTC_COTURN_IP=$EXPERIMENT_MALU_WEBRTC_COTURN_IP
EXPERIMENT_MALU_WEBRTC_COTURN_USER=$EXPERIMENT_MALU_WEBRTC_COTURN_USER
EXPERIMENT_MALU_WEBRTC_COTURN_PASSWORD=$EXPERIMENT_MALU_WEBRTC_COTURN_PASSWORD
EXPERIMENT_MALU_WEBRTC_COTURN_EXTRA=$EXPERIMENT_MALU_WEBRTC_COTURN_EXTRA
EOF

ln -sf ".env.$NODE_ENV" .env
