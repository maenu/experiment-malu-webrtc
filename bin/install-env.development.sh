#!/usr/bin/env bash

cd "$(dirname "$0")/.."

EXPERIMENT_MALU_WEBRTC_HOST="$(hostname --fqdn)"
EXPERIMENT_MALU_WEBRTC_HTTP_PORT="3080"
EXPERIMENT_MALU_WEBRTC_HTTPS_PORT="3443"
EXPERIMENT_MALU_WEBRTC_CA_CERT="$(pwd)/ca/cert.pem"
EXPERIMENT_MALU_WEBRTC_CA_KEY="$(pwd)/ca/key.pem"
EXPERIMENT_MALU_WEBRTC_CA_HOST="$EXPERIMENT_MALU_WEBRTC_HOST"
EXPERIMENT_MALU_WEBRTC_PEERJS_PATH="/peer"
EXPERIMENT_MALU_WEBRTC_PEERJS_PORT="3081"
EXPERIMENT_MALU_WEBRTC_PEERJS_KEY="$EXPERIMENT_MALU_WEBRTC_HOST"
EXPERIMENT_MALU_WEBRTC_COTURN_IP=$(dig +short "${EXPERIMENT_MALU_WEBRTC_HOST}" | head -n1)
EXPERIMENT_MALU_WEBRTC_COTURN_USER="$EXPERIMENT_MALU_WEBRTC_HOST"
EXPERIMENT_MALU_WEBRTC_COTURN_PASSWORD="$EXPERIMENT_MALU_WEBRTC_HOST"
EXPERIMENT_MALU_WEBRTC_COTURN_EXTRA="--syslog --log-file=stdout -v -m 4 --min-port=49152 --max-port=49272"

cat << EOF > ".env.development.local"
EXPERIMENT_MALU_WEBRTC_HOST=$EXPERIMENT_MALU_WEBRTC_HOST
EXPERIMENT_MALU_WEBRTC_HTTP_PORT=$EXPERIMENT_MALU_WEBRTC_HTTP_PORT
EXPERIMENT_MALU_WEBRTC_HTTPS_PORT=$EXPERIMENT_MALU_WEBRTC_HTTPS_PORT
EXPERIMENT_MALU_WEBRTC_CA_CERT=$EXPERIMENT_MALU_WEBRTC_CA_CERT
EXPERIMENT_MALU_WEBRTC_CA_KEY=$EXPERIMENT_MALU_WEBRTC_CA_KEY
EXPERIMENT_MALU_WEBRTC_CA_HOST=$EXPERIMENT_MALU_WEBRTC_CA_HOST
EXPERIMENT_MALU_WEBRTC_PEERJS_PATH=$EXPERIMENT_MALU_WEBRTC_PEERJS_PATH
EXPERIMENT_MALU_WEBRTC_PEERJS_PORT=$EXPERIMENT_MALU_WEBRTC_PEERJS_PORT
EXPERIMENT_MALU_WEBRTC_PEERJS_KEY=$EXPERIMENT_MALU_WEBRTC_PEERJS_KEY
EXPERIMENT_MALU_WEBRTC_COTURN_IP=$EXPERIMENT_MALU_WEBRTC_COTURN_IP
EXPERIMENT_MALU_WEBRTC_COTURN_USER=$EXPERIMENT_MALU_WEBRTC_COTURN_USER
EXPERIMENT_MALU_WEBRTC_COTURN_PASSWORD=$EXPERIMENT_MALU_WEBRTC_COTURN_PASSWORD
EXPERIMENT_MALU_WEBRTC_COTURN_EXTRA=$EXPERIMENT_MALU_WEBRTC_COTURN_EXTRA
EOF
